// How wide text is at a height.
function textWidth(text, h) { return String(text).length ? (String(text).length * 6 - 2) * h / 6 : 0; }
// Text as strokes (lists of points, mm), its bottom left at (x, y).
function textStrokes(text, x, y, h) {
  var k = h / 6, out = [];
  String(text).toUpperCase().split('').forEach(function(ch, i) {
    (STROKE_FONT[ch] || []).forEach(function(line) {
      out.push(line.map(function(p) { return { x: x + (i * 6 + p[0]) * k, y: y + p[1] * k }; }));
    });
  });
  return out;
}

